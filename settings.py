# ================================================================
#                        turn 이 무엇인가
# ================================================================
#
#  turn = 주고받기 한 번 = 내가 친 말 1개 + 봇이 한 답 1개.
#
#  내 말만도 아니고 봇 답만도 아닙니다.  둘이 붙어 있는 한 쌍입니다.
#
# ----------------------------------------------------------------
#  실물로 봅니다.  아래는 WoS 데이터셋의 진짜 대화입니다.
#  (wos_train_full.jsonl, guid = wos-v1_train_00001, 도메인 = 관광)
# ----------------------------------------------------------------
#
#   turn 1  나  : "쇼핑을 하려는데 서울 서쪽에 있을까요?"
#           봇  : "서울 서쪽에 쇼핑이 가능한 곳이라면 노량진 수산물 도매시장이 있습니다."
#
#   turn 2  나  : "오 네 거기 주소 좀 알려주세요."
#           봇  : "노량진 수산물 도매시장의 주소는 서울 동작구 93806입니다."
#
#   turn 3  나  : "알려주시는김에 연락처랑 평점도 좀 알려주세요."
#           봇  : "그럼. 연락처는 6182006591이고 평점은 4점입니다."
#
#   turn 4  나  : "와 감사합니다."
#           봇  : "감사합니다."
#
#  이 대화는 4 turn 입니다.  줄로 세면 8줄이지만 turn 으로 세면 4 입니다.
#  화면에 보이는 말풍선 개수와 turn 개수는 다릅니다.  말풍선 8개 = turn 4개.
#
# ----------------------------------------------------------------
#  코드에서 turn 은 어떻게 생겼나
# ----------------------------------------------------------------
#
#  app.py 의 chat(message, history) 가 받는 history 는 이렇게 생겼습니다.
#
#      history = [
#          ("쇼핑을 하려는데 서울 서쪽에 있을까요?", "...노량진 수산물 도매시장이 있습니다."),
#          ("오 네 거기 주소 좀 알려주세요.",        "...서울 동작구 93806입니다."),
#          ("알려주시는김에 연락처랑 평점도...",      "...연락처는 6182006591이고 평점은 4점입니다."),
#      ]
#
#  괄호 한 쌍이 turn 1개입니다.  len(history) 가 곧 지금까지의 turn 수입니다.
#  위 예에서 len(history) == 3 이고, 지금 내가 "와 감사합니다" 를 치면
#  그것이 message 로 따로 들어옵니다.  아직 history 에는 없습니다.
#
#      history  = 지나간 turn 들          (내 말 + 봇 답이 짝지어 저장됨)
#      message  = 방금 친 말 하나          (아직 봇이 답을 안 했으니 짝이 없음)
#
# ----------------------------------------------------------------
#  HISTORY_TURNS 는 그 짝을 뒤에서 몇 개 볼지 정합니다
# ----------------------------------------------------------------
#
#      recent = history[-HISTORY_TURNS:]
#
#  HISTORY_TURNS = 2 이고 위 history(3개) 라면 recent 는 뒤에서 2개입니다.
#
#      recent = [ turn 2, turn 3 ]        <-- turn 1 은 빠집니다
#
#  turn 1 에서 내가 말한 "쇼핑" 과 "서울 서쪽" 은 봇에게 안 넘어갑니다.
#  화면에는 그대로 보이는데 봇은 못 봅니다.  이것이 "범위 밖으로 밀림" 입니다.
#
#  WoS 원본 데이터는 이 문제가 없습니다.  turn 3 의 state 를 보면
#
#      ["관광-종류-쇼핑", "관광-지역-서울 서쪽", "관광-이름-노량진 수산물 도매시장"]
#
#  turn 1 에서 나온 "쇼핑" 과 "서울 서쪽" 이 turn 3 에도 그대로 있습니다.
#  사람은 앞에 말한 것을 기억하니까요.
#
#  WoS 의 state 가 정답지이고, 내 봇의 "채운 칸" 이 내 답안입니다.
#  둘이 어긋나는 지점을 찾는 것이 이번 주 과제입니다.
#
# ----------------------------------------------------------------
#  주의 - 어제 본 "넘긴 것: N개" 는 turn 수가 아닙니다
# ----------------------------------------------------------------
#
#  수업 중 실습 앱은 화면에 "넘긴 것: N개" 를 띄웠습니다.
#  그 N 은 turn 수가 아니라 **모델에게 보낸 메시지 개수** 입니다.
#
#      turn 1개  ->  메시지 2개 (user 1 + model 1)
#      거기에 방금 친 말 1개를 더한다
#
#      넘긴 것 = HISTORY_TURNS x 2 + 1
#
#      HISTORY_TURNS = 5  ->  넘긴 것 11개
#      HISTORY_TURNS = 6  ->  넘긴 것 13개
#      HISTORY_TURNS = 7  ->  넘긴 것 15개
#
#  홀수만 나오는 이유가 이것입니다.  마지막 +1 이 방금 친 말입니다.
#  turn 을 7로 올렸는데 15가 뜬 것은 고장이 아니라 세는 단위가 달랐던 것입니다.
#
# ================================================================


